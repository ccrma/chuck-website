#!/usr/bin/env python3
"""
build_site_index.py - build the site-content index used by the search page.

    python3 build_site_index.py [FOLDER]

Reads the HTML pages and Markdown sources under FOLDER (default: the whole
site), strips menus, headers and footers, splits each page into sections at
its headings, and writes one JSON file. Markdown files with a matching .html
page link to that page. By default the index goes in ../search/site.json,
found relative to THIS SCRIPT, so a script kept in /doc/ writes into the
site's /search/ folder (which must already exist). Re-run it whenever pages
change.

Left out automatically: pages made by make_example_pages.py (their code is
covered by the examples index), the example page template, pages marked
<meta name="robots" content="noindex">, and everything in the folder the
index is written to (that's the search page itself).

The output is deterministic (no timestamps), so if nothing changed the file
is left untouched and your uploads/commits stay quiet.
"""
import argparse
import gzip
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import quote

INDEX_VERSION = 1  # the search page checks this; bump both if the format changes
GENERATED_MARKER = "Generated by make_example_pages.py"
TEMPLATE_NAME = "webchuck-example-template.html"  # the example page template is not a real page

# Tags whose whole contents are ignored
SKIP_TAGS = {"head", "script", "style", "noscript", "svg", "nav", "header", "footer",
             "aside", "template", "iframe", "button", "select"}
# Elements whose class or id contains one of these words are ignored too
SKIP_WORDS = {"header", "footer", "nav", "navbar", "menu", "sidebar", "breadcrumb", "breadcrumbs"}
SKIP_ROLES = {"navigation", "banner", "contentinfo"}
VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input",
             "link", "meta", "source", "track", "wbr"}
# Tags that separate words (so "</p><p>" doesn't glue two words together)
BLOCK_TAGS = {"p", "div", "li", "ul", "ol", "dl", "dt", "dd", "tr", "td", "th", "table", "br",
              "hr", "pre", "blockquote", "section", "article", "main", "figure", "figcaption",
              "caption", "details", "summary", "form", "fieldset", "h1", "h2", "h3", "h4", "h5", "h6"}
HEADINGS = {"h1": 1, "h2": 2, "h3": 3, "h4": 4, "h5": 5, "h6": 6}


def clean(text):
    return re.sub(r"\s+", " ", text).strip()


def is_excluded(parts, excludes):
    """True if any excluded folder (name or a/b path) appears in the path parts."""
    for ex in excludes:
        ex = [p for p in ex.replace("\\", "/").split("/") if p]
        n = len(ex)
        if n and any(list(parts[i:i + n]) == ex for i in range(len(parts) - n + 1)):
            return True
    return False


class PageParser(HTMLParser):
    """Collects the page title and a list of sections: {id, heading, text}."""

    def __init__(self, split_level, skip_names):
        super().__init__(convert_charrefs=True)
        self.split_level = split_level
        self.skip_tags = SKIP_TAGS | skip_names
        self.skip_words = SKIP_WORDS | skip_names
        self.title_parts, self.in_title, self.title_done = [], False, False
        self.noindex = False
        self.skip_tag, self.skip_depth = None, 0
        self.sections = []
        self.cur = {"id": "", "heading": "", "parts": []}
        self.in_heading = None            # tag name while inside a heading we split at
        self.heading = {"id": "", "parts": []}
        self.pending_anchor = ""          # <a name="x"></a> seen just before a heading

    # -- helpers --
    def _should_skip(self, tag, attrs):
        if tag in VOID_TAGS:
            return False
        if tag in self.skip_tags:
            return True
        a = dict(attrs)
        if (a.get("role") or "").lower() in SKIP_ROLES:
            return True
        words = re.split(r"[^a-z0-9]+", f"{a.get('class') or ''} {a.get('id') or ''}".lower())
        return any(w in self.skip_words for w in words if w)

    def _add(self, text):
        (self.heading["parts"] if self.in_heading else self.cur["parts"]).append(text)

    def _close_heading(self):
        if self.in_heading:
            h = self.heading
            self.cur = {"id": h["id"], "heading": clean("".join(h["parts"])), "parts": []}
            self.in_heading = None

    def _flush(self):
        text = clean("".join(self.cur["parts"]))
        if self.cur["heading"] or text:
            self.sections.append({"id": self.cur["id"], "heading": self.cur["heading"], "text": text})
        self.cur = {"id": "", "heading": "", "parts": []}

    def finish(self):
        self._close_heading()
        self._flush()

    # -- parser callbacks --
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title" and not self.title_done and self.skip_tag in (None, "head"):
            self.in_title = True
            return
        if tag == "meta" and (a.get("name") or "").lower() == "robots" \
                and "noindex" in (a.get("content") or "").lower():
            self.noindex = True
        if tag == "body" and self.skip_tag == "head":     # a <head> that was never closed
            self.skip_tag, self.skip_depth = None, 0
        if self.skip_tag is not None:
            if tag == self.skip_tag:
                self.skip_depth += 1
            return
        if self._should_skip(tag, attrs):
            self.skip_tag, self.skip_depth = tag, 1
            return

        if tag in HEADINGS and HEADINGS[tag] <= self.split_level:
            self._close_heading()
            self._flush()
            self.in_heading = tag
            self.heading = {"id": a.get("id") or self.pending_anchor, "parts": []}
            self.pending_anchor = ""
            return
        if tag == "a":
            anchor = a.get("id") or a.get("name")
            if anchor:
                if self.in_heading:
                    if not self.heading["id"]:
                        self.heading["id"] = anchor
                else:
                    self.pending_anchor = anchor
        if tag in BLOCK_TAGS:
            self._add(" ")

    def handle_endtag(self, tag):
        if tag == "title":
            if self.in_title:
                self.in_title, self.title_done = False, True
            return
        if self.skip_tag is not None:
            if tag == self.skip_tag:
                self.skip_depth -= 1
                if self.skip_depth == 0:
                    self.skip_tag = None
            return
        if self.in_heading and tag == self.in_heading:
            self._close_heading()
            return
        if tag in BLOCK_TAGS:
            self._add(" ")

    def handle_data(self, data):
        if self.in_title:
            self.title_parts.append(data)
            return
        if self.skip_tag is not None:
            return
        if data.strip():
            self.pending_anchor = ""
        self._add(data)


def read_text(path):
    raw = path.read_bytes()
    try:
        return raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        print(f"warning: {path} is not UTF-8, reading it as Latin-1")
        return raw.decode("latin-1")


def size(n):
    return f"{n / 1024:.0f} KB" if n < 1024 * 1024 else f"{n / 1024 / 1024:.2f} MB"


def main():
    ap = argparse.ArgumentParser(description="Build the site-content index (site.json) for the search page.")
    ap.add_argument("folder", nargs="?", type=Path,
                    help="folder to scan recursively (default: the whole site root)")
    ap.add_argument("--site-root", type=Path, metavar="DIR",
                    help="the folder your server serves as / (default: the folder above this script's folder)")
    ap.add_argument("--out", type=Path,
                    help="output file (default: ../search/site.json, relative to this script)")
    ap.add_argument("--exclude", action="append", default=[], metavar="DIR",
                    help="skip a folder, by name or path such as old/docs (repeatable)")
    ap.add_argument("--skip", action="append", default=[], metavar="NAME",
                    help="also ignore elements with this tag name, class or id, e.g. outlineDiv (repeatable)")
    ap.add_argument("--split-level", type=int, default=3, metavar="N",
                    help="split pages into sections at headings h1..hN (default: 3)")
    ap.add_argument("--ext", nargs="+", default=[".html", ".htm", ".md"],
                    help="page file extensions to read (default: .html .htm .md)")
    ap.add_argument("--dry-run", action="store_true", help="report what would be indexed, write nothing")
    args = ap.parse_args()

    if not 1 <= args.split_level <= 6:
        sys.exit("--split-level must be between 1 and 6.")
    script_dir = Path(__file__).resolve().parent
    site_root = (args.site_root or script_dir.parent).resolve()
    root = (args.folder or site_root).resolve()
    if not root.is_dir():
        sys.exit(f"Not a folder: {root}")
    try:
        root.relative_to(site_root)
    except ValueError:
        sys.exit(f"{root} isn't inside the site root {site_root}, so page addresses can't be worked out.\n"
                 "Pass --site-root with the folder your server serves as /.")

    out = args.out or script_dir.parent / "search" / "site.json"
    if not out.parent.is_dir():
        sys.exit(f"The folder {out.parent} doesn't exist, so there's nowhere to write the index.\n"
                 "By default the index goes in ../search/ next to this script's folder. "
                 "Create that folder, or choose a location with --out.")
    out_dir = out.resolve().parent

    exts = {e.lower() if e.startswith(".") else "." + e.lower() for e in args.ext}
    skip_names = {s.lower() for s in args.skip}
    pages, generated, noindex, empty = [], 0, 0, 0

    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or p.suffix.lower() not in exts:
            continue
        if any(part.startswith(".") for part in rel.parts) or is_excluded(rel.parts[:-1], args.exclude):
            continue
        if p.resolve().is_relative_to(out_dir) or p.name == TEMPLATE_NAME:
            continue
        html = read_text(p)
        if GENERATED_MARKER in html[:600]:
            generated += 1
            continue
        try:
            parser = PageParser(args.split_level, skip_names)
            parser.feed(html)
            parser.close()
            parser.finish()
        except Exception as err:  # malformed markup the parser can't handle
            print(f"warning: skipped {p} ({err})")
            continue
        if parser.noindex:
            noindex += 1
            continue
        if not parser.sections:
            empty += 1
            continue

        title = clean("".join(parser.title_parts))
        if not title:
            title = next((s["heading"] for s in parser.sections if s["heading"]), "") or p.stem
        url_page = p
        if p.suffix.lower() == ".md":
            html_page = p.with_suffix(".html")
            if html_page.is_file():
                url_page = html_page
        url_path = url_page.relative_to(site_root).as_posix()
        for index_name in ("index.html", "index.htm"):
            if url_path == index_name or url_path.endswith("/" + index_name):
                url_path = url_path[: -len(index_name)]
        pages.append({"url": "/" + quote(url_path), "title": title, "sections": parser.sections})

    if not pages:
        sys.exit("No pages found to index.")
    pages.sort(key=lambda pg: pg["url"])

    data = json.dumps({"version": INDEX_VERSION, "count": len(pages), "pages": pages},
                      ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    sections = [s for pg in pages for s in pg["sections"]]
    text_bytes = sum(len(s["text"].encode("utf-8")) + len(s["heading"].encode("utf-8")) for s in sections)
    # a page's first section is its top, which needs no anchor
    no_anchor = sum(1 for pg in pages for s in pg["sections"][1:] if s["heading"] and not s["id"])

    print(f"Indexed {len(pages)} pages in {len(sections)} sections ({size(text_bytes)} of text).")
    print(f"{out}: {size(len(data))}, about {size(len(gzip.compress(data, 6)))} gzipped.")
    skipped = [f"{n} {what}" for n, what in ((generated, "generated example pages"),
                                              (noindex, "noindex pages"),
                                              (empty, "pages with no readable text")) if n]
    if skipped:
        print("Left out: " + ", ".join(skipped) + ".")
    if no_anchor:
        print(f"{no_anchor} sections have headings with no id, so their results link to the top of the page. "
              'Adding id="..." to those headings makes results jump straight to the section.')
    biggest = sorted(pages, key=lambda pg: -sum(len(s["text"]) for s in pg["sections"]))[:5]
    print("Largest pages:")
    for pg in biggest:
        print(f"  {sum(len(s['text']) for s in pg['sections']):>9,} characters  {pg['url']}"
              f" ({len(pg['sections'])} sections)")

    if args.dry_run:
        print("Dry run: nothing written.")
    elif out.exists() and out.read_bytes() == data:
        print("Index already up to date.")
    else:
        out.write_bytes(data)
        print("Wrote index.")


if __name__ == "__main__":
    main()
