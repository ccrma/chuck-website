#!/usr/bin/env python3
"""
make_example_pages.py - generate a WebChucK page next to every .ck file.

    python3 make_example_pages.py /path/to/examples

For every X.ck under the folder, writes X.html beside it, built from
web-example-template.html. Safe to re-run: unchanged pages are left alone,
and existing .html files that this script did not generate are never
overwritten unless you pass --force.
"""
import argparse
import html
import re
import sys
from pathlib import Path
from urllib.parse import quote

TEMPLATE_NAME = "webchuck-example-template.html"
MARKER_KEY = "Generated by make_example_pages.py"
MARKER = f"<!-- {MARKER_KEY} from the matching .ck file. Edits will be overwritten. -->"

# The places the template gets filled in. Elements are found by id, so
# attribute order, quote style, extra classes/styles and the tag name can change.
TITLE_TAG = re.compile(r"(<title\b[^>]*>)Title(</title>)", re.I)
TITLE_SPAN = re.compile(r"""(<(\w+)\b[^>]*(?<![\w-])id=["']title["'][^>]*>)Title(</\2>)""", re.I)
CODE_SLOT = re.compile(r"""(<script\b[^>]*(?<![\w-])id=["']chuck["'][^>]*>)// chuck code(</script>)""", re.I)
# Optional: an element with id="download" and href="example.ck" (a link) or
# data-href="example.ck" (a button) gets the page's own .ck filename
DOWNLOAD_TAG = re.compile(r"""<\w+\b[^>]*(?<![\w-])id=["']download["'][^>]*>""", re.I)
DOWNLOAD_HREF = re.compile(r"""((?<![\w-])(?:data-)?href=["'])example\.ck(["'])""", re.I)
DOCTYPE = re.compile(r"<!doctype html>\n", re.I)


def is_excluded(parts, excludes):
    """True if any excluded folder (name or a/b path) appears in the path parts."""
    for ex in excludes:
        ex = [p for p in ex.replace("\\", "/").split("/") if p]
        n = len(ex)
        if n and any(list(parts[i:i + n]) == ex for i in range(len(parts) - n + 1)):
            return True
    return False


def read_text(path):
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        print(f"warning: {path} is not UTF-8, reading it as Latin-1")
        text = raw.decode("latin-1")
    return text.replace("\r\n", "\n").replace("\r", "\n")


def escape_for_template_literal(code):
    """
    The template wraps this text in a JavaScript template literal when the page
    loads, so backslashes, backticks and ${ must be escaped to come out
    unchanged (a ChucK "\\n" would otherwise turn into a real newline).
    </script and <!-- are escaped so they can't end or confuse the script tag.
    """
    code = code.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    code = re.sub(r"</(script)", r"<\\/\1", code, flags=re.I)
    return code.replace("<!--", "<\\!--")


def load_template(path):
    template = path.read_text(encoding="utf-8")
    for what, rx in (("<title>Title</title>", TITLE_TAG),
                     ('an element with id="title" containing the text Title', TITLE_SPAN),
                     ('a <script id="chuck"> containing // chuck code', CODE_SLOT)):
        found = len(rx.findall(template))
        if found != 1:
            sys.exit(f"Template {path} needs exactly one {what} (found {found}).")
    if DOCTYPE.search(template):
        return DOCTYPE.sub(lambda m: m[0] + MARKER + "\n", template, count=1)
    return MARKER + "\n" + template


def has_download_slot(template):
    return any(DOWNLOAD_HREF.search(m[0]) for m in DOWNLOAD_TAG.finditer(template))


def fill_download(page, filename):
    href = quote(filename)
    return DOWNLOAD_TAG.sub(lambda m: DOWNLOAD_HREF.sub(lambda h: h[1] + href + h[2], m[0]), page)


def render(template, code, title, filename):
    t = html.escape(title, quote=False)
    page = TITLE_TAG.sub(lambda m: m[1] + t + m[2], template)
    page = TITLE_SPAN.sub(lambda m: m[1] + t + m[3], page)
    page = fill_download(page, filename)
    # Code goes in last, with the first line right after the tag and the
    # closing tag right after the last line (like a <pre>).
    body = escape_for_template_literal(code.rstrip())
    return CODE_SLOT.sub(lambda m: m[1] + body + m[2], page)


def has_marker(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return MARKER_KEY in f.read(600)


def main():
    ap = argparse.ArgumentParser(description="Generate a WebChucK page next to every .ck file.")
    ap.add_argument("folder", type=Path, help="folder to search recursively for .ck files")
    ap.add_argument("--template", type=Path,
                    help=f"template file (default: {TEMPLATE_NAME} in the folder, then next to this script)")
    ap.add_argument("--exclude", action="append", default=[], metavar="DIR",
                    help="skip a folder, by name or path such as osc/multicast (repeatable)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite existing .html files even if this script didn't generate them")
    ap.add_argument("--prune", action="store_true",
                    help="delete generated pages whose .ck file no longer exists")
    ap.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    args = ap.parse_args()

    root = args.folder
    if not root.is_dir():
        sys.exit(f"Not a folder: {root}")

    candidates = [args.template] if args.template else \
        [root / TEMPLATE_NAME, Path(__file__).resolve().parent / TEMPLATE_NAME]
    template_path = next((p for p in candidates if p.is_file()), None)
    if template_path is None:
        sys.exit(f"Couldn't find the template. Looked for: {', '.join(str(c) for c in candidates)}")
    template = load_template(template_path)
    if not has_download_slot(template):
        print('note: template has no id="download" element with href="example.ck" or data-href="example.ck", so no download link is added.')

    ck_files, pages = [], []
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or any(part.startswith(".") for part in rel.parts):
            continue
        if is_excluded(rel.parts[:-1], args.exclude):
            continue
        if p.suffix.lower() == ".ck":
            ck_files.append(p)
        elif p.suffix.lower() == ".html":
            pages.append(p)

    created, updated, skipped, unchanged = [], [], [], 0
    for ck in ck_files:
        out = ck.with_suffix(".html")
        page = render(template, read_text(ck), ck.stem, ck.name)
        if out.exists():
            if not args.force and not has_marker(out):
                skipped.append(out)
                continue
            if out.read_text(encoding="utf-8", errors="replace") == page:
                unchanged += 1
                continue
            updated.append(out)
        else:
            created.append(out)
        if not args.dry_run:
            out.write_text(page, encoding="utf-8", newline="\n")

    expected = {ck.with_suffix(".html") for ck in ck_files}
    orphans = [pg for pg in pages if pg not in expected and has_marker(pg)]
    if args.prune and not args.dry_run:
        for pg in orphans:
            pg.unlink()

    def show(paths):
        for p in paths:
            print(f"  {p.relative_to(root)}")

    verb = "Would write" if args.dry_run else "Wrote"
    print(f"{len(ck_files)} .ck files found.")
    print(f"{verb} {len(created)} new and {len(updated)} updated pages; {unchanged} already up to date.")
    if args.dry_run:
        show(created + updated)
    if skipped:
        print(f"\nLeft alone ({len(skipped)} existing .html files not made by this script; --force overwrites):")
        show(skipped)
    if orphans:
        action = "Would delete" if args.dry_run and args.prune else \
                 "Deleted" if args.prune else "Generated pages with no matching .ck (--prune deletes them)"
        print(f"\n{action}:")
        show(orphans)


if __name__ == "__main__":
    main()
