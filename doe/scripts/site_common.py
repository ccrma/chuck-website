"""
Shared settings and helpers for the example and search scripts.

Everything that depends on how the site is laid out is in the first block.
If the folders ever move, change them here and nowhere else.
"""
import os
from pathlib import Path
from urllib.parse import unquote, urlparse

# ---- Site layout ---------------------------------------------------------------
# The folder holding these scripts is /doe/scipts/. The site root is the folder above it.
TOOLS_DIR = Path(__file__).resolve().parent
SITE_ROOT = TOOLS_DIR.parent.parent

# Folders, written relative to the site root
EXAMPLE_FOLDERS = ["doc/examples", "chugl/examples"]  # every .ck in these is searchable
PAGE_FOLDERS = ["doc/examples"]                       # pages are made here (chugl pages come from another script)
LEFT_OUT_FOLDERS = ["legacy", "smuck"]                         # never read, edited or searched
SEARCH_FOLDER = "search"                              # the search page and the indexes the scripts write

# Folders that hold no real pages: left out of link fixing and site search
NON_PAGE_FOLDERS = LEFT_OUT_FOLDERS + [TOOLS_DIR.name, SEARCH_FOLDER]

# Absolute links to these hosts count as links within the site
SITE_HOSTS = ["chuck.stanford.edu"]

# Files in the scripts folder
IGNORE_FILE = TOOLS_DIR / "ignored-examples.txt"
TEMPLATE_FILE = TOOLS_DIR / "webchuck-example-template.html"

# Written into every generated page so the scripts can tell them from hand-written ones
GENERATED_MARKER = "Generated by make_example_pages.py"


# ---- Paths ---------------------------------------------------------------------
def folder(name):
    """A layout folder such as "doc/examples" as a path on disk."""
    return SITE_ROOT / name


def site_path(path):
    """A file's address from the site root, like "doc/examples/basic/a.ck"."""
    return Path(path).resolve().relative_to(SITE_ROOT).as_posix()


def is_inside(path, folder_name):
    """True if path is the folder or something inside it."""
    here = site_path(path)
    return here == folder_name or here.startswith(folder_name + "/")


def require_inside_site(path):
    """Exit with a clear message if path isn't under the site root."""
    try:
        Path(path).resolve().relative_to(SITE_ROOT)
    except ValueError:
        raise SystemExit(f"{path} is outside the site ({SITE_ROOT}).")


def local_file(page, url, hosts=SITE_HOSTS):
    """The file on disk that a link in a page points at, or None if the link goes
    to another website or outside the site."""
    parts = urlparse(url)
    if (parts.scheme or parts.netloc) and parts.netloc.lower() not in {h.lower() for h in hosts}:
        return None
    link_path = unquote(parts.path)
    start = SITE_ROOT if link_path.startswith("/") else Path(page).parent
    target = Path(os.path.normpath(start / link_path.lstrip("/")))
    try:
        target.relative_to(SITE_ROOT)
    except ValueError:
        return None
    return target


def find_files(start, extensions, skip=()):
    """Sorted files under start with one of the extensions (like {".ck"}).

    Hidden files and folders are skipped, and so are the folders in skip."""
    found = []
    for dirpath, dirnames, filenames in os.walk(start):
        here = Path(dirpath)
        dirnames[:] = [d for d in dirnames
                       if not d.startswith(".") and not any(is_inside(here / d, s) for s in skip)]
        for name in filenames:
            if not name.startswith(".") and Path(name).suffix.lower() in extensions:
                found.append(here / name)
    return sorted(found)


# ---- Reading files -------------------------------------------------------------
def read_text(path):
    """A text file as a string with plain \\n line endings (UTF-8, or Latin-1 if it isn't)."""
    raw = Path(path).read_bytes()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        print(f"warning: {path} is not UTF-8, reading it as Latin-1")
        text = raw.decode("latin-1")
    return text.replace("\r\n", "\n").replace("\r", "\n")


def is_generated(html_path):
    """True if make_example_pages.py made this page."""
    with open(html_path, encoding="utf-8", errors="replace") as f:
        return GENERATED_MARKER in f.read(600)


def size_text(n_bytes):
    return f"{n_bytes / 1024:.0f} KB" if n_bytes < 1024 * 1024 else f"{n_bytes / 1024 / 1024:.2f} MB"


# ---- The ignore list -----------------------------------------------------------
class IgnoreList:
    """Examples that should not get a web page, read from ignored-examples.txt.

    One rule per line. The .ck is optional.
      test          any file called test.ck, in any folder
      basic/test    only basic/test.ck
      serial/       everything in a folder called serial
    """

    def __init__(self):
        self.files = []    # "test", "basic/test"
        self.folders = []  # "serial/"

    def add(self, line):
        rule = line.split("#", 1)[0].strip().lower().replace("\\", "/")
        if not rule:
            return
        if rule.endswith("/"):
            self.folders.append(rule)
        else:
            self.files.append(rule[:-3] if rule.endswith(".ck") else rule)

    def matches(self, ck_path):
        """True if this .ck file is on the list."""
        path = site_path(ck_path).lower()            # doc/examples/basic/test.ck
        if path.endswith(".ck"):
            path = path[:-3]
        if any(path == rule or path.endswith("/" + rule) for rule in self.files):
            return True
        folders_of_path = "/" + path.rsplit("/", 1)[0] + "/"   # /doc/examples/basic/
        return any("/" + rule in folders_of_path for rule in self.folders)


def load_ignore_list():
    rules = IgnoreList()
    if IGNORE_FILE.is_file():
        for line in read_text(IGNORE_FILE).splitlines():
            rules.add(line)
    return rules


# ---- Examples and their pages --------------------------------------------------
def is_example(ck_path):
    """True if the .ck file is inside one of the example folders."""
    return any(is_inside(ck_path, f) for f in EXAMPLE_FOLDERS)


def has_page(ck_path, ignored):
    """True if links should use the example's .html page: the page exists and the
    example isn't on the ignore list. Otherwise links use the .ck file."""
    return Path(ck_path).with_suffix(".html").is_file() and not ignored.matches(ck_path)
